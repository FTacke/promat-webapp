def resolve_ui_language(ui_lang: str | None) -> str:
    if isinstance(ui_lang, str) and ui_lang in SUPPORTED_UI_LANGUAGES:
        return ui_lang
    return DEFAULT_UI_LANGUAGE


def translate(ui_lang: str | None, key: str, **kwargs: object) -> str:
    language = resolve_ui_language(ui_lang)
    value = TRANSLATIONS.get(language, {}).get(key)
    if value is None:
        value = TRANSLATIONS[DEFAULT_UI_LANGUAGE].get(key, key)
    if kwargs:
        return value.format(**kwargs)
    return value


def translate_many(ui_lang: str | None, key_map: Mapping[str, str]) -> dict[str, str]:
    return {name: translate(ui_lang, key) for name, key in key_map.items()}